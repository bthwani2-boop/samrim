import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const contractPath = path.join(root, "services/identity/contracts/identity.openapi.yaml");
const outputPath = path.join(root, "services/identity/clients/generated/identity-types.ts");
const source = fs.readFileSync(contractPath, "utf8");
const sourceSha = crypto.createHash("sha256").update(source).digest("hex");

const schemaNames = [
  "OtpRequest",
  "ActivationRequest",
  "ActivationChallenge",
  "LoginRequest",
  "RefreshRequest",
  "Permission",
  "ActorIdentity",
  "TokenPair",
  "ActorView",
  "ActorSearchPage",
  "IssueActivationRequest",
  "SessionInfo",
];

function schemaBlock(name) {
  const marker = "    " + name + ":\n";
  const start = source.indexOf(marker);
  if (start < 0) throw new Error("missing OpenAPI schema " + name);
  const tail = source.slice(start + marker.length);
  const next = tail.search(/^    [A-Za-z0-9_]+:\n/m);
  return next < 0 ? tail : tail.slice(0, next);
}

function refName(value) {
  const match = value.match(/#\/components\/schemas\/([A-Za-z0-9_]+)/);
  if (!match) throw new Error("unsupported schema ref " + value);
  return match[1];
}

function scalarLiteral(value) {
  const trimmed = value.trim();
  if (trimmed === "true" || trimmed === "false" || /^-?[0-9]+(?:\.[0-9]+)?$/.test(trimmed)) return trimmed;
  return JSON.stringify(trimmed.replace(/^["']|["']$/g, ""));
}

function typeFor(block, context) {
  const ref = block.match(/^\s+\$ref:\s*["']?([^\n"']+)["']?/m);
  if (ref) return refName(ref[1]);

  const constant = block.match(/^\s+const:\s*(.+)$/m);
  if (constant) return scalarLiteral(constant[1]);

  const inlineEnum = block.match(/^\s+enum:\s*\[([^\]]+)\]/m);
  if (inlineEnum) {
    return inlineEnum[1].split(",").map((part) => scalarLiteral(part)).join(" | ");
  }

  const type = block.match(/^\s+type:\s*([A-Za-z]+)\s*$/m)?.[1];
  switch (type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array": {
      const itemsIndex = block.indexOf("\n          items:");
      if (itemsIndex < 0) throw new Error("array schema missing items: " + context);
      return "ReadonlyArray<" + typeFor(block.slice(itemsIndex), context + "[]") + ">";
    }
    case "object": {
      const additional = block.match(/additionalProperties:\s*\n\s+type:\s*([A-Za-z]+)/);
      if (!additional) throw new Error("unsupported object property shape: " + context);
      const valueType = additional[1] === "boolean" ? "boolean" : additional[1] === "string" ? "string" : null;
      if (!valueType) throw new Error("unsupported map value type: " + context);
      return "Readonly<Record<string, " + valueType + ">>";
    }
    default:
      throw new Error("unsupported property type in " + context);
  }
}

function renderSchema(name) {
  const block = schemaBlock(name);
  if (!/^      type: object$/m.test(block)) throw new Error(name + " must be an object schema");
  const requiredMatch = block.match(/^      required:\s*\[([^\]]*)\]/m);
  const required = new Set(
    requiredMatch
      ? requiredMatch[1].split(",").map((part) => part.trim()).filter(Boolean)
      : [],
  );
  const propertiesMarker = "      properties:\n";
  const propertiesStart = block.indexOf(propertiesMarker);
  if (propertiesStart < 0) throw new Error(name + " is missing properties");
  const propertyRegion = block.slice(propertiesStart + propertiesMarker.length);
  const matches = [...propertyRegion.matchAll(/^        ([A-Za-z0-9_]+):\n/g)];
  const lines = [];
  for (let index = 0; index < matches.length; index++) {
    const current = matches[index];
    const next = matches[index + 1];
    const property = current[1];
    const valueBlock = propertyRegion.slice(
      current.index + current[0].length,
      next ? next.index : propertyRegion.length,
    );
    const optional = required.has(property) ? "" : "?";
    lines.push("  readonly " + property + optional + ": " + typeFor(valueBlock, name + "." + property) + ";");
  }
  if (lines.length === 0) throw new Error(name + " has no generated properties");
  return "export type " + name + " = {\n" + lines.join("\n") + "\n};";
}

export function generateIdentityTypes() {
  const header = [
    "/**",
    " * AUTO-GENERATED from services/identity/contracts/identity.openapi.yaml.",
    " * Source SHA256: " + sourceSha,
    " * Generated by tools/dev/generate-identity-types.mjs. DO NOT EDIT.",
    " */",
    "",
  ].join("\n");
  return header + schemaNames.map(renderSchema).join("\n\n") + "\n";
}

const generated = generateIdentityTypes();
const check = process.argv.includes("--check");
if (check) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error("IDENTITY_GENERATED_TYPES=DRIFT");
    process.exit(1);
  }
  console.log("IDENTITY_GENERATED_TYPES=PASS sha256=" + sourceSha);
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, generated, "utf8");
  console.log("IDENTITY_GENERATED_TYPES=WRITTEN sha256=" + sourceSha);
}
