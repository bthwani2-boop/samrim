import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sourcePath = path.join(root, "backend/internal/security/password_blocklist_source.txt");
const outputPath = path.join(root, "backend/internal/security/password_blocklist_generated.go");
const sourceVersion = "identity-passwords-v2";

const values = [...new Set(fs.readFileSync(sourcePath, "utf8").split(/\r?\n/).map((line) => line.trim()).filter((line) => line && !line.startsWith("#")).map((line) => line.normalize("NFC").toLowerCase()))].sort();
if (values.length === 0) throw new Error("password blocklist source is empty");
const canonical = values.join("\n") + "\n";
const checksum = crypto.createHash("sha256").update(canonical).digest("hex");
const unformatted = `// Code generated by services/identity/tools/generate-password-blocklist.mjs; DO NOT EDIT.\n// Source: services/identity/backend/internal/security/password_blocklist_source.txt\n// Source version: ${sourceVersion}\n// Canonical values SHA-256: ${checksum}\n\npackage security\n\nvar passwordBlocklistGenerated = map[string]struct{}{\n${values.map((value) => `\t${JSON.stringify(value)}: {},`).join("\n")}\n}\n`;
const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "identity-blocklist-"));
const temporaryPath = path.join(temporaryDirectory, "password_blocklist_generated.go");
let rendered;
try {
  fs.writeFileSync(temporaryPath, unformatted, "utf8");
  execFileSync("gofmt", ["-w", temporaryPath], { encoding: "utf8" });
  rendered = fs.readFileSync(temporaryPath, "utf8");
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

if (process.argv.includes("--check")) {
  const current = fs.readFileSync(outputPath, "utf8");
  if (current !== rendered) {
    console.error("password blocklist generated artifact is stale; run identity:blocklist:generate");
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputPath, rendered, "utf8");
}
console.log(`IDENTITY_BLOCKLIST_GENERATION=PASS version=${sourceVersion} entries=${values.length} sha256=${checksum}`);
