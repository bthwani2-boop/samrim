CREATE TABLE dsh.store_operational_availability (
    store_id text PRIMARY KEY REFERENCES dsh.stores(id) ON DELETE CASCADE,
    schedule_mode text NOT NULL DEFAULT 'ALWAYS_OPEN',
    weekly_schedule jsonb NOT NULL DEFAULT '[]'::jsonb,
    paused boolean NOT NULL DEFAULT false,
    pause_reason text,
    pause_until timestamptz,
    preparation_minutes integer,
    unavailable_fulfillment_modes text[] NOT NULL DEFAULT ARRAY[]::text[],
    version integer NOT NULL DEFAULT 1,
    updated_by_actor_id text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT store_operational_availability_schedule_mode_chk
        CHECK (schedule_mode IN ('ALWAYS_OPEN','WEEKLY')),
    CONSTRAINT store_operational_availability_schedule_chk
        CHECK (
            (schedule_mode = 'ALWAYS_OPEN' AND weekly_schedule = '[]'::jsonb)
            OR (schedule_mode = 'WEEKLY' AND jsonb_typeof(weekly_schedule) = 'array')
        ),
    CONSTRAINT store_operational_availability_pause_chk
        CHECK (
            (paused = false AND pause_reason IS NULL AND pause_until IS NULL)
            OR (paused = true AND pause_reason IS NOT NULL AND length(btrim(pause_reason)) BETWEEN 2 AND 500)
        ),
    CONSTRAINT store_operational_availability_preparation_chk
        CHECK (preparation_minutes IS NULL OR preparation_minutes BETWEEN 1 AND 1440),
    CONSTRAINT store_operational_availability_modes_chk
        CHECK (unavailable_fulfillment_modes <@ ARRAY['BTHWANI_CAPTAIN','PARTNER_CAPTAIN','CUSTOMER_PICKUP']::text[]),
    CONSTRAINT store_operational_availability_modes_unique_chk
        CHECK (cardinality(unavailable_fulfillment_modes) = cardinality(ARRAY(SELECT DISTINCT unnest(unavailable_fulfillment_modes)))),
    CONSTRAINT store_operational_availability_version_chk CHECK (version > 0),
    CONSTRAINT store_operational_availability_actor_chk CHECK (length(btrim(updated_by_actor_id)) BETWEEN 1 AND 128)
);

INSERT INTO dsh.store_operational_availability(store_id, schedule_mode, weekly_schedule, paused, unavailable_fulfillment_modes, version, updated_by_actor_id)
SELECT id, 'ALWAYS_OPEN', '[]'::jsonb, false, ARRAY[]::text[], 1, 'system:migration:085'
