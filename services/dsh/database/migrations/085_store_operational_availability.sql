ON CONFLICT(store_id) DO NOTHING;

CREATE TABLE dsh.store_operational_availability_idempotency (
    idempotency_key text PRIMARY KEY,
    request_hash text NOT NULL,
    store_id text NOT NULL REFERENCES dsh.stores(id) ON DELETE CASCADE,
    acting_actor_id text NOT NULL,
    result_version integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT store_operational_availability_idem_key_chk CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
    CONSTRAINT store_operational_availability_idem_hash_chk CHECK (request_hash ~ '^[a-f0-9]{64}$'),
    CONSTRAINT store_operational_availability_idem_actor_chk CHECK (length(btrim(acting_actor_id)) BETWEEN 1 AND 128),
    CONSTRAINT store_operational_availability_idem_version_chk CHECK (result_version > 0)
);

CREATE TABLE dsh.store_operational_availability_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id text NOT NULL REFERENCES dsh.stores(id) ON DELETE RESTRICT,
    event_type text NOT NULL,
    idempotency_key text NOT NULL UNIQUE REFERENCES dsh.store_operational_availability_idempotency(idempotency_key) ON DELETE RESTRICT,
    correlation_id text NOT NULL,
    acting_actor_id text NOT NULL,
    authority_source text NOT NULL,
    expected_version integer NOT NULL,
    result_version integer NOT NULL,
    request_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT store_operational_availability_audit_event_chk CHECK (event_type = 'operational_availability_changed'),
    CONSTRAINT store_operational_availability_audit_correlation_chk CHECK (length(btrim(correlation_id)) BETWEEN 8 AND 128),
    CONSTRAINT store_operational_availability_audit_actor_chk CHECK (length(btrim(acting_actor_id)) BETWEEN 1 AND 128),
    CONSTRAINT store_operational_availability_audit_authority_chk CHECK (authority_source IN ('STORE_OWNER','STORE_GRANT','OPERATOR')),
    CONSTRAINT store_operational_availability_audit_version_chk CHECK (expected_version > 0 AND result_version = expected_version + 1),
    CONSTRAINT store_operational_availability_audit_hash_chk CHECK (request_hash ~ '^[a-f0-9]{64}$')
);

CREATE INDEX store_operational_availability_updated_idx
    ON dsh.store_operational_availability(updated_at DESC, store_id);
