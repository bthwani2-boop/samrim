package http

import (
	"archive/zip"
	"bytes"
	"encoding/json"
	"mime/multipart"
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"
)

func TestFinanceEvidenceUploadRejectsExternallySuppliedSettlementExport(t *testing.T) {
	var xlsx bytes.Buffer
	archive := zip.NewWriter(&xlsx)
	for _, name := range []string{"[Content_Types].xml", "xl/workbook.xml"} {
		entry, err := archive.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := entry.Write([]byte("<Types/>")); err != nil {
			t.Fatal(err)
		}
	}
	if err := archive.Close(); err != nil {
		t.Fatal(err)
	}

	for _, purpose := range []string{
		"SETTLEMENT_BATCH_EXPORT",
		"  settlement_batch_export  ",
		"SeTtLeMeNt_BaTcH_ExPoRt",
	} {
		t.Run(strings.TrimSpace(purpose), func(t *testing.T) {
			var body bytes.Buffer
			form := multipart.NewWriter(&body)
			if err := form.WriteField("purpose", purpose); err != nil {
				t.Fatal(err)
			}
			file, err := form.CreateFormFile("file", "forged-settlement.xlsx")
			if err != nil {
				t.Fatal(err)
			}
			if _, err := file.Write(xlsx.Bytes()); err != nil {
				t.Fatal(err)
			}
			if err := form.Close(); err != nil {
				t.Fatal(err)
			}

			request := httptest.NewRequest(http.MethodPost, "/wlt/v1/operator/finance-evidence-documents", &body)
			request.Header.Set("Content-Type", form.FormDataContentType())
			request.Header.Set("Authorization", "Bearer service-token")
			request.Header.Set("X-Acting-Actor-ID", "finance-operator")
			request.Header.Set("X-Correlation-ID", "upload-correlation-123")
			request.Header.Set("Idempotency-Key", "upload-idempotency-123")
			response := httptest.NewRecorder()
			(&Server{serviceToken: "service-token"}).uploadFinanceEvidenceDocument(response, request)

			var result struct {
				Error struct {
					Code    string `json:"code"`
					Message string `json:"message"`
				} `json:"error"`
			}
			if err := json.Unmarshal(response.Body.Bytes(), &result); err != nil {
				t.Fatalf("decode rejection: %v: %s", err, response.Body.String())
			}
			if response.Code != http.StatusBadRequest || result.Error.Code != "INVALID_INPUT" ||
				!strings.Contains(result.Error.Message, "generated by WLT") {
				t.Fatalf("untrusted settlement XLSX was not rejected at upload boundary: status=%d response=%s", response.Code, response.Body.String())
			}
		})
	}
}
